"""Batch-convert one track's Briefings Markdown files into one PDF.

This uses the same MarkdownService as the Matn UI, so Arabic fonts,
bookmarks, RTL layout, and the existing visual styling stay consistent.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

from services.markdown_service import MarkdownService


def natural_key(path: Path) -> tuple:
    return tuple(int(part) if part.isdigit() else part.casefold() for part in re.split(r"(\d+)", path.name))


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Convert a track's Briefings Markdown files to one PDF")
    parser.add_argument("--input-dir", required=True, type=Path, help="Directory containing Briefings Markdown files")
    parser.add_argument("--output", required=True, type=Path, help="Destination PDF path")
    parser.add_argument("--title", required=True, help="Track title")
    parser.add_argument("--track-path", default="", help="Relative path on manhaji.app")
    parser.add_argument("--track-url", default="", help="Public track URL when available")
    parser.add_argument("--notebook-id", default="")
    parser.add_argument("--package-id", default="")
    parser.add_argument("--font-family", default="IBM Plex Sans Arabic")
    parser.add_argument("--include-toc", action="store_true")
    parser.add_argument("--cover-page", action="store_true")
    parser.add_argument("--no-bookmarks", action="store_true")
    return parser


def main() -> int:
    args = build_parser().parse_args()
    input_dir = args.input_dir.resolve()
    output = args.output.resolve()
    if not input_dir.is_dir():
        raise SystemExit(f"Input directory does not exist: {input_dir}")

    markdown_files = sorted(input_dir.glob("*.md"), key=natural_key)
    if not markdown_files:
        raise SystemExit(f"No Markdown files found in: {input_dir}")

    output.parent.mkdir(parents=True, exist_ok=True)
    options = {
        **MarkdownService.DEFAULT_OPTIONS,
        "title": args.title,
        "header_text": args.title,
        "font_family": args.font_family,
        "include_toc": args.include_toc,
        "cover_page": args.cover_page,
        "bookmarks_enabled": not args.no_bookmarks,
        "direction": "rtl",
        "text_align": "justify",
        "author": "Zemam Apps",
        "publisher": "Zemam Apps",
        "creator": "Matn — Smart PDF Workspace",
        "producer": "Matn Markdown to PDF (Chromium)",
        "subject": "Track PDF generated by Matn | Zemam Apps | manhaji.app",
        "keywords": ", ".join(filter(None, [
            "Matn", "PDF", "Zemam Apps", "zemamapps.com", "manhaji.app",
            args.track_path, args.track_url, args.notebook_id, args.package_id,
        ])),
        "footer_text": "Matn — Smart PDF Workspace by Zemam Apps | manhaji.app",
    }
    MarkdownService.convert_to_pdf(
        [str(path) for path in markdown_files],
        str(output),
        options,
    )
    print(f"created={output}")
    print(f"source_count={len(markdown_files)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
